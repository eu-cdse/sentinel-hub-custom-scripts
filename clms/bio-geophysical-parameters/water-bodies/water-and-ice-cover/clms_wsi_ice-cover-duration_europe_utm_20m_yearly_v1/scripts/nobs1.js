const factor = 1;
const offset = 0;
function setup() {
    return {
        input: ["NOBS1", "dataMask"],
        output: [
            { id: "default", bands: 4, sampleType: "UINT8" },
            { id: "index", bands: 1, sampleType: "FLOAT32" },
            { id: "browserStats", bands: 1, sampleType: "FLOAT32" },
            { id: "dataMask", bands: 1 },
        ],
    };
}

function evaluatePixel(samples) {
    const originalValue = samples.NOBS1;
    const val = originalValue * factor + offset;
    const min = 0;
    const max = 366;
    const stats = val >= min && val <= max ? val : NaN;
    const dataMask = samples.dataMask;

    const EXCLUDED_VALUES = [];
    const isExcluded =
        dataMask === 0 || EXCLUDED_VALUES.includes(originalValue);

    if (isExcluded) {
        return {
            default: [0, 0, 0, 0],
            index: [NaN],
            browserStats: [NaN],
            dataMask: [dataMask],
        };
    }

    const imgVals = visualizer.process(val);
    const alpha = originalValue === 65535 ? 180 : 255;
    return {
        default: imgVals.concat(dataMask * alpha),
        index: [val],
        browserStats: [stats],
        dataMask: [dataMask],
    };
}

